    fun translate(text: String, language: UserSettings.Language): String = when (language) {
        UserSettings.Language.CHINESE -> chineseOnly(text)
        UserSettings.Language.ENGLISH -> englishByLength
            .fold(text) { value, (chinese, translation) -> value.replace(chinese, translation) }
            .let(::englishOnly)
    }

    // 每个 Text 重组都会走一遍 translate，排序只做一次
    private val englishByLength by lazy { english.entries.sortedByDescending { it.key.length }.map { it.key to it.value } }

    private fun chineseOnly(text: String): String {
        val translated = text
            .replace("no physical keyboard", "未检测到实体键盘")
            .replace("conflicts", "个冲突")
            .replace("disabled", "个已禁用")
            .replace("KEYBOARD", "键盘")
        if (!translated.contains(Regex("[\\p{IsHan}]"))) return translated
        val parts = translated.split(" · ")
        if (parts.size == 1) return translated
        return parts.filter { it.contains(Regex("[\\p{IsHan}]")) }.joinToString(" · ").ifEmpty { translated }
    }

    private fun englishOnly(text: String): String = dedupeEnglishLabels(text
        .replace('「', '\'')
        .replace('」', '\'')
        .replace('（', '(')
        .replace('）', ')')
        .replace('：', ':')
        .replace('，', ',')
        .replace('。', '.')
        .replace('；', ';'))

    private fun dedupeEnglishLabels(text: String): String {
        val parts = text.split(" · ").toMutableList()
        var index = 0
        while (index < parts.lastIndex) {
            val left = parts[index].trim()
            val right = parts[index + 1].trim()
            if (left.equals(right, ignoreCase = true) ||
                left.startsWith(right, ignoreCase = true) ||
                right.startsWith(left, ignoreCase = true)
            ) {
                parts[index] = if (left.length >= right.length) left else right
                parts.removeAt(index + 1)
            } else {
                index++
            }
        }
        return parts.joinToString(" · ")
    }
