    /** 逐个码位拆开：一串连写的单码位符号。 */
    private fun chars(raw: String): List<String> =
        raw.codePoints().toArray().map { String(Character.toChars(it)) }.filter { it.isNotBlank() }

    private fun range(from: Int, to: Int): List<String> = (from..to).map { String(Character.toChars(it)) }

