/**
 * 「输入符号」的符号表。
 *
 * 按键盘上找不到、又常要打的那几类分组：标点、数学、箭头、货币、单位、序号、各种文字的字母……
 * 连续的码位段（圈号、假名、注音）按区间生成，其余逐个列出，免得手抄漏字。
 * 空白和不可见字符单独一组，界面上显示 [nameOf] 给出的名字而不是空格子。
 */
