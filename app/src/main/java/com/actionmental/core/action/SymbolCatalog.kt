    /** 空白、控制、格式字符在格子里看不见，用名字代替。其余返回 null，格子直接显示符号本身。 */
    fun nameOf(symbol: String): String? = invisibleNames[symbol]

    private val invisibleNames = mapOf(
        "\u3000" to "全角空格",
        "\u00A0" to "不换行空格",
        "\u2002" to "半身空格",
        "\u2003" to "全身空格",
        "\u2009" to "窄空格",
        "\u200A" to "极窄空格",
        "\u202F" to "窄不换行空格",
        "\u200B" to "零宽空格",
        "\u200C" to "零宽不连字",
        "\u200D" to "零宽连字",
        "\u2060" to "词连接符",
        "\uFEFF" to "零宽不换行",
        "\u200E" to "左至右标记",
        "\u200F" to "右至左标记",
        "\u00AD" to "软连字符",
        "\t" to "制表符",
        "\n" to "换行",
    )

    /** `U+00A9`，多码位的（emoji 带变体选择符）用空格连起来。 */
    fun codePoints(text: String): String =
        text.codePoints().toArray().joinToString(" ") { "U+" + Integer.toHexString(it).uppercase().padStart(4, '0') }

    /** 给编辑页预选分组：当前符号在哪一组。 */
    fun groupOf(symbol: String): Group? = groups.firstOrNull { symbol in it.symbols }
